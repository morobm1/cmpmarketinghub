import { verifyReqAuth } from './_auth.js';

/**
 * Email AI Generate API
 * POST - Proxy to AI provider (OpenAI/Anthropic) for email generation
 * Currently uses mock provider logic server-side.
 * When API keys are configured, will proxy to real AI providers.
 */
export async function handler(event) {
  const user = verifyReqAuth(event);
  if (!user) return { statusCode: 401, body: 'Unauthorized' };

  if (event.httpMethod !== 'POST') {
    return { statusCode: 405, body: 'Method not allowed' };
  }

  const json = (data) => ({ statusCode: 200, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) });

  try {
    const body = JSON.parse(event.body || '{}');
    const { prompt, enrichedPrompt, provider } = body;

    const openaiKey = process.env.OPENAI_API_KEY;
    const anthropicKey = process.env.ANTHROPIC_API_KEY;

    // If we have an API key, proxy to the real AI provider
    if (openaiKey && (!provider || provider === 'openai')) {
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${openaiKey}`,
        },
        body: JSON.stringify({
          model: 'gpt-4o',
          messages: [
            { role: 'system', content: enrichedPrompt || 'You are an email designer. Generate email blocks as JSON.' },
            { role: 'user', content: prompt || 'Generate a marketing email' },
          ],
          temperature: 0.7,
          max_tokens: 4000,
        }),
      });
      const data = await response.json();
      return json({
        success: true,
        provider: 'openai',
        content: data.choices?.[0]?.message?.content || '',
        raw: data,
      });
    }

    if (anthropicKey && provider === 'anthropic') {
      const response = await fetch('https://api.anthropic.com/v1/messages', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-api-key': anthropicKey,
          'anthropic-version': '2023-06-01',
        },
        body: JSON.stringify({
          model: 'claude-sonnet-4-20250514',
          max_tokens: 4000,
          system: enrichedPrompt || 'You are an email designer. Generate email blocks as JSON.',
          messages: [
            { role: 'user', content: prompt || 'Generate a marketing email' },
          ],
        }),
      });
      const data = await response.json();
      return json({
        success: true,
        provider: 'anthropic',
        content: data.content?.[0]?.text || '',
        raw: data,
      });
    }

    // Fallback: mock AI response (same pattern as the frontend mock provider)
    return json({
      success: true,
      provider: 'mock',
      content: JSON.stringify({
        blocks: [
          { type: 'header', data: { style: { backgroundColor: '#2563eb', paddingTop: 16, paddingBottom: 16, paddingLeft: 24, paddingRight: 24, textAlign: 'center' }, visible: true, logoUrl: '', logoAlt: 'Logo', logoWidth: 160, preheaderText: '', backgroundColor: '#2563eb' } },
          { type: 'text', data: { style: { backgroundColor: '', textColor: '#333333', paddingTop: 24, paddingBottom: 16, paddingLeft: 32, paddingRight: 32, textAlign: 'center' }, visible: true, content: 'AI Generated Email', fontSize: 24, fontWeight: 700, lineHeight: 1.3 } },
          { type: 'text', data: { style: { backgroundColor: '', textColor: '#555555', paddingTop: 8, paddingBottom: 24, paddingLeft: 32, paddingRight: 32, textAlign: 'left' }, visible: true, content: 'This is a placeholder generated by the mock AI provider. Configure OPENAI_API_KEY or ANTHROPIC_API_KEY in your environment variables to enable real AI generation.', fontSize: 16, fontWeight: 400, lineHeight: 1.6 } },
          { type: 'button', data: { style: { backgroundColor: '', paddingTop: 8, paddingBottom: 32, paddingLeft: 32, paddingRight: 32, textAlign: 'center' }, visible: true, label: 'Learn More', url: '#', backgroundColor: '#2563eb', textColor: '#ffffff', borderRadius: 8, fontSize: 16, fontWeight: 700, paddingX: 32, paddingY: 14, alignment: 'center', fullWidth: false } },
        ],
        subjectLines: ['Check out what\'s new!', 'You don\'t want to miss this'],
        previewTexts: ['See our latest updates and offers', 'Exciting news inside'],
      }),
      message: 'Mock AI response. Set OPENAI_API_KEY or ANTHROPIC_API_KEY for real generation.',
    });
  } catch (err) {
    console.error('email-ai-generate error:', err);
    return { statusCode: 500, body: 'Internal server error' };
  }
}
